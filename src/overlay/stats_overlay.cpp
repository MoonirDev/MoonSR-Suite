// StatsOverlay implementation: "<rendered>/<total>" frame counter drawn into the presented frame.
//
// Threading model: one StatsOverlayImpl is created, used and destroyed on a single thread (the engine pipeline thread,
// which owns the D3D11 immediate context). None of its methods are thread-safe.
//
// How it works:
//  * Glyph atlas: the characters "0123456789/.- " are rendered once with GDI (Segoe UI Bold, greyscale anti-aliasing,
//    NOT ClearType) into a 32-bit DIB; the green channel is kept as coverage and uploaded as an immutable R8 texture.
//    The atlas is one row of equal-sized cells. Every cell has `pad` empty texels on each side so the outline taps in
//    the pixel shader never reach a neighbouring glyph. Digits share one advance (tabular), so the text does not
//    jitter as numbers change. The atlas is rebuilt only when the text height changes (target height changed).
//  * Draw: the text is formatted with std::to_chars into a fixed char buffer. The per-glyph instance data (pixel rect
//    + atlas rect, 32 bytes each) is written to a dynamic vertex buffer only when the numbers or the target size
//    changed; otherwise Draw only sets state and issues one instanced draw. No heap allocation and no GDI in the
//    steady state.
//  * One draw: each glyph is a TRIANGLESTRIP quad (SV_VertexID); the pixel shader outputs a premultiplied white glyph
//    with a dark outline (see shaders/overlay/overlay_ps.hlsl) blended with ONE / INV_SRC_ALPHA.
#include "overlay/stats_overlay.h"

#include "core/log.h"

#include <algorithm>
#include <array>
#include <charconv>
#include <cmath>
#include <cstring>
#include <vector>

// Compiled shader bytecode (generated by fxc at build time, see shaders/CMakeLists.txt).
#include "g_ps_overlay.h"
