// CursorOverlay implementation: software cursor drawn into the presented frame + system cursor hiding.
//
// Threading model: one CursorOverlay is created, used and destroyed on a single thread (the engine pipeline thread,
// which owns the D3D11 immediate context). None of its methods are thread-safe. MagInitialize / MagUninitialize are
// called on that same thread (the Magnification API requires the pair on one thread).
//
// Cursor images: on a new HCURSOR the shape is extracted with GetIconInfo + GetDIBits (always read as 32-bit
// top-down DIBs; the 1-bit masks are converted by GDI to black/white) into up to two BGRA8 textures:
//   normal (paint) - premultiplied colour + coverage;
//   invert (XOR)   - XOR colour for mask pixels with AND = 1 and a non-zero XOR/colour value (e.g. the I-beam).
// Both are drawn in ONE pass with dual-source blending (SrcBlend = INV_DEST_COLOR, DestBlend = SRC1_COLOR), which
// gives `c + d(1-a)` for paint texels and `s(1-d) + d(1-s)` (exact XOR for 0/1 channels, i.e. invert for white) for
// XOR texels, and stays exact under bilinear filtering where the two kinds meet. See shaders/cursor/cursor_ps.hlsl.
// Dual-source blending is part of the D3D11 feature level 10_0+ baseline, so no capability check is needed at 11_0.
// A shared 1x1 zero texture stands in for a missing paint or XOR texture.
// Kinds handled:
//   32-bit colour with alpha  -> normal only (GDI stores straight alpha; premultiplied on the CPU at extraction)
//   colour, all alpha zero    -> AND mask: AND=0 opaque colour, AND=1 & colour!=0 XOR, AND=1 & colour=0 transparent
//   monochrome (AND over XOR) -> AND/XOR: 00 black, 01 white, 10 transparent, 11 invert
// Up to kCacheSize shapes are cached by HCURSOR (LRU). When the cursor shape changes to a cached handle, the entry is
// re-validated (hotspot and bitmap size via GetIconInfo) so a destroyed-and-reused handle with different geometry is
// re-extracted. Steady state (same shape) makes no GDI calls and no heap allocations.
